#!/usr/bin/env bash
# Render api/.env from three Bitwarden vault items:
#   self-sensored/jwt      — JWT_SECRET
#   self-sensored/db       — Postgres password for role `self_sensored`
#   self-sensored/ollama   — OLLAMA_API_KEY
#
# Requires: bw (Bitwarden CLI), vault unlocked via `export BW_SESSION=$(bw unlock --raw)`.
# See scripts/README.md for full setup.

set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ENV_FILE="${ENV_FILE:-$REPO_ROOT/api/.env}"

die() { echo "error: $*" >&2; exit 1; }

command -v bw >/dev/null 2>&1 || die "bw CLI not installed. Run: brew install bitwarden-cli"
[[ -n "${BW_SESSION:-}" ]] || die 'BW_SESSION not set. Run: export BW_SESSION="$(bw unlock --raw)"'

status="$(bw status | sed -n 's/.*"status":"\([^"]*\)".*/\1/p')"
[[ "$status" == "unlocked" ]] || die "Bitwarden vault is ${status:-unreachable}. Run: export BW_SESSION=\"\$(bw unlock --raw)\""

fetch() {
    local name="$1"
    local value
    value="$(bw get password "$name" 2>/dev/null)" || die "vault item '$name' not found or has no password"
    [[ -n "$value" ]] || die "vault item '$name' returned empty password"
    printf '%s' "$value"
}

echo "Fetching secrets from Bitwarden..." >&2
JWT_SECRET="$(fetch self-sensored/jwt)"
DB_PASS="$(fetch self-sensored/db)"
OLLAMA_API_KEY="$(fetch self-sensored/ollama)"

# Hardcoded non-secret values. Keep in sync with api/.env.example.
DB_HOST="192.168.1.104"
DB_PORT="5432"
DB_NAME="self_sensored"
DB_USER="self_sensored"
OLLAMA_BASE_URL="https://ollama.com/v1"
OLLAMA_MODEL="gpt-oss:120b-cloud"
RUST_LOG="self_sensored_api=info,tower_http=info"
API_HOST="0.0.0.0"
API_PORT="3000"
LOG_FORMAT="${LOG_FORMAT:-json}"

# URL-encode the DB password so characters like + / = from openssl rand -base64
# survive intact inside the URL.
urlencode() {
    local raw="$1"
    local i c
    for (( i = 0; i < ${#raw}; i++ )); do
        c="${raw:i:1}"
        case "$c" in
            [a-zA-Z0-9.~_-]) printf '%s' "$c" ;;
            *) printf '%%%02X' "'$c" ;;
        esac
    done
}
DB_PASS_ENC="$(urlencode "$DB_PASS")"

umask 077
tmp="$(mktemp "${ENV_FILE}.XXXXXX")"
trap 'rm -f "$tmp"' EXIT

cat > "$tmp" <<EOF
# Generated by scripts/render-env.sh from Bitwarden. Do not edit by hand.
# To rotate: scripts/rotate-secrets.sh
# To regenerate without rotation: scripts/render-env.sh
DATABASE_URL=postgres://${DB_USER}:${DB_PASS_ENC}@${DB_HOST}:${DB_PORT}/${DB_NAME}
JWT_SECRET=${JWT_SECRET}
OLLAMA_API_KEY=${OLLAMA_API_KEY}
OLLAMA_BASE_URL=${OLLAMA_BASE_URL}
OLLAMA_MODEL=${OLLAMA_MODEL}
RUST_LOG=${RUST_LOG}
API_HOST=${API_HOST}
API_PORT=${API_PORT}
LOG_FORMAT=${LOG_FORMAT}
EOF

chmod 600 "$tmp"
mv "$tmp" "$ENV_FILE"
trap - EXIT

echo "Wrote $ENV_FILE (mode 600)." >&2
